/* Inside gateForm Submit Listener */
gateForm.addEventListener("submit", (e) => {
  e.preventDefault();
  
  // Use parseFloat for decimal comparison
  const userAnswer = parseFloat(mathAnswer.value.trim());

  // Use Math.abs to safely handle floating-point rounding
  if (!isNaN(userAnswer) && Math.abs(userAnswer - correctAnswer) < 0.001) {
    // Unlock site
    gateOverlay.classList.add("hidden");
    mainContent.classList.remove("hidden");

    if (bgMusic) {
      bgMusic.volume = 0.5;
      bgMusic.play().catch(() => {});
    }

    triggerConfetti();
  } else {
    errorMsg.innerText = "Incorrect answer! Hint: Evaluate 10³ + 5, then subtract 1/25.";
    const gateCard = document.querySelector(".gate-card");
    if (gateCard) {
      gateCard.classList.add("shake");
      setTimeout(() => gateCard.classList.remove("shake"), 400);
    }
  }
});
/* ==========================================================================
   RENDER STUDENT CARDS
   ========================================================================== */
function renderCards(data) {
  cardsGrid.innerHTML = "";
  studentCount.innerText = `${data.length} Student${data.length === 1 ? '' : 's'}`;

  if (data.length === 0) {
    cardsGrid.innerHTML = `<p style="grid-column: 1/-1; text-align:center; color: var(--text-muted); padding: 40px 0;">No student messages found.</p>`;
    return;
  }

  data.forEach((student) => {
    const card = document.createElement("div");
    card.className = "student-card";
    card.onclick = () => openModal(student);

    card.innerHTML = `
      <div class="avatar-wrapper">
        <img src="${student.image}" alt="${student.name}" loading="lazy">
        <div class="card-heart-badge">
          <i class="fa-solid fa-sun"></i>
        </div>
      </div>
      <h3>${student.name}</h3>
      <p class="card-message">"${student.message}"</p>
      <div class="read-more-btn">
        <span>Read Full Message</span>
        <i class="fa-solid fa-arrow-right"></i>
      </div>
    `;

    cardsGrid.appendChild(card);
  });
}

/* ==========================================================================
   SEARCH / FILTER FUNCTION
   ========================================================================== */
searchInput.addEventListener("input", (e) => {
  const query = e.target.value.toLowerCase().trim();
  const filtered = studentsData.filter(
    (s) =>
      s.name.toLowerCase().includes(query) ||
      s.message.toLowerCase().includes(query)
  );
  renderCards(filtered);
});

/* ==========================================================================
   MODAL FUNCTIONALITY
   ========================================================================== */
function openModal(student) {
  modalAvatar.src = student.image;
  modalName.innerText = student.name;
  
  modalMessage.innerText = student.message;

  messageModal.classList.remove("hidden");
}

closeModal.addEventListener("click", () => {
  messageModal.classList.add("hidden");
});

window.addEventListener("click", (e) => {
  if (e.target === messageModal) {
    messageModal.classList.add("hidden");
  }
});

/* ==========================================================================
   CONFETTI ANIMATION (Sunflower Yellow & Amber Colors)
   ========================================================================== */
function triggerConfetti() {
  if (typeof confetti === "function") {
    const duration = 2.5 * 1000;
    const end = Date.now() + duration;

    (function frame() {
      confetti({
        particleCount: 4,
        angle: 60,
        spread: 55,
        origin: { x: 0 },
        colors: ["#f59e0b", "#fbbf24", "#d97706", "#ffffff"]
      });
      confetti({
        particleCount: 4,
        angle: 120,
        spread: 55,
        origin: { x: 1 },
        colors: ["#f59e0b", "#fbbf24", "#d97706", "#ffffff"]
      });

      if (Date.now() < end) {
        requestAnimationFrame(frame);
      }
    })();
  }
}

/* ==========================================================================
   FLOATING SUNFLOWERS BACKGROUND CANVAS
   ========================================================================== */
function initFloatingSunflowers() {
  const canvas = document.getElementById("heartCanvas");
  const ctx = canvas.getContext("2d");

  let width = (canvas.width = window.innerWidth);
  let height = (canvas.height = window.innerHeight);

  window.addEventListener("resize", () => {
    width = canvas.width = window.innerWidth;
    height = canvas.height = window.innerHeight;
  });

  // Generate individual sunflower particles
  const flowers = Array.from({ length: 22 }, () => ({
    x: Math.random() * width,
    y: Math.random() * height,
    size: Math.random() * 10 + 12,
    speedY: Math.random() * 0.8 + 0.3,
    rotation: Math.random() * Math.PI * 2,
    rotSpeed: (Math.random() - 0.5) * 0.02,
    opacity: Math.random() * 0.5 + 0.3
  }));

  function drawSunflower(x, y, radius, opacity, rotation) {
    ctx.save();
    ctx.translate(x, y);
    ctx.rotate(rotation);
    ctx.globalAlpha = opacity;

    const petals = 12;
    // Draw 12 Bright Yellow Petals
    ctx.fillStyle = "#fbbf24";
    for (let i = 0; i < petals; i++) {
      ctx.beginPath();
      ctx.rotate((Math.PI * 2) / petals);
      ctx.ellipse(0, radius, radius * 0.3, radius * 0.8, 0, 0, Math.PI * 2);
      ctx.fill();
    }

    // Draw Dark Brown Center Seed Disk
    ctx.beginPath();
    ctx.arc(0, 0, radius * 0.55, 0, Math.PI * 2);
    ctx.fillStyle = "#78350f";
    ctx.fill();

    ctx.restore();
  }

  function animate() {
    ctx.clearRect(0, 0, width, height);
    flowers.forEach((f) => {
      f.y -= f.speedY;
      f.rotation += f.rotSpeed;
      if (f.y < -30) {
        f.y = height + 30;
        f.x = Math.random() * width;
      }
      drawSunflower(f.x, f.y, f.size, f.opacity, f.rotation);
    });
    requestAnimationFrame(animate);
  }

  animate();
}

