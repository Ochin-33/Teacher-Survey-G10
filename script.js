/* ==========================================================================
   INTERACTIVE CANDLE BLOWING LOGIC (Web Audio API)
   ========================================================================== */
let isCandleOut = false;

const candleFlame = document.getElementById("candleFlame");
const smokeEffect = document.getElementById("smokeEffect");
const enableMicBtn = document.getElementById("enableMicBtn");
const fallbackBlowBtn = document.getElementById("fallbackBlowBtn");
const micStatus = document.getElementById("micStatus");

// Function to extinguish flame
function blowOutCandle() {
  if (isCandleOut) return;
  isCandleOut = true;

  if (candleFlame) candleFlame.classList.add("out");
  if (smokeEffect) {
    smokeEffect.classList.remove("hidden");
    smokeEffect.classList.add("active");
  }

  if (micStatus) {
    micStatus.innerText = "🎉 Wish granted! Happy Birthday! 🌻";
  }

  // Trigger celebratory confetti burst
  if (typeof triggerConfetti === "function") {
    triggerConfetti();
  }
}

// Fallback click listener
if (fallbackBlowBtn) {
  fallbackBlowBtn.addEventListener("click", blowOutCandle);
}

// Microphone sound analysis
if (enableMicBtn) {
  enableMicBtn.addEventListener("click", async () => {
    if (isCandleOut) return;

    try {
      const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
      const audioContext = new (window.AudioContext || window.webkitAudioContext)();
      const analyser = audioContext.createAnalyser();
      const microphone = audioContext.createMediaStreamSource(stream);
      
      analyser.fftSize = 256;
      microphone.connect(analyser);

      const dataArray = new Uint8Array(analyser.frequencyBinCount);
      if (micStatus) micStatus.innerText = "Listening... Blow into your mic now! 💨";

      function checkAudioVolume() {
        if (isCandleOut) return;

        analyser.getByteFrequencyData(dataArray);
        
        // Calculate average audio level
        let sum = 0;
        for (let i = 0; i < dataArray.length; i++) {
          sum += dataArray[i];
        }
        const averageVolume = sum / dataArray.length;

        // Threshold for blowing air into microphone
        if (averageVolume > 45) { 
          blowOutCandle();
          // Stop mic stream after blowing
          stream.getTracks().forEach(track => track.stop());
          return;
        }

        requestAnimationFrame(checkAudioVolume);
      }

      checkAudioVolume();
    } catch (err) {
      console.error("Microphone access denied or unsupported:", err);
      if (micStatus) {
        micStatus.innerText = "Microphone access unavailable. Click the button to blow instead!";
      }
    }
  });
}
